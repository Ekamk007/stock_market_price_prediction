def create_tabular_features(df, target_col='Close', lags=[1, 2, 3, 5, 10]):
    df_feat = df.copy()

    # Create historical lag features (t-1, t-2, etc.)
    for lag in lags:
        df_feat[f"{target_col}_lag_{lag}"] = df_feat[target_col].shift(lag)

    # Drop rows with NaN values created by shifting
    df_feat = df_feat.dropna()

    # Separate features (X) and target variable (y)
    # Exclude the current day's Close, Rolling_Mean, and Rolling_Std from features to avoid data leakage
    feature_cols = [col for col in df_feat.columns if col not in ['Close', 'Rolling_Mean', 'Rolling_Std']]

    X = df_feat[feature_cols]
    y = df_feat[target_col]

    return X, y

